"""Regenerate the event catalogue artifacts from app/modules/analytics/taxonomy.py.

    python scripts/gen_analytics_catalog.py                       # rewrite docs/ANALYTICS_EVENTS.md catalogue block
    python scripts/gen_analytics_catalog.py --kotlin PATH/AnalyticsEvents.kt
    python scripts/gen_analytics_catalog.py --check               # exit 1 if the doc block is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.modules.analytics.taxonomy import EVENTS, FUNNELS, OBJECT_TYPES, SCHEMA_VERSION  # noqa: E402

BEGIN = "<!-- BEGIN GENERATED CATALOG -->"
END = "<!-- END GENERATED CATALOG -->"
CATEGORY_TITLES = {
    "lifecycle": "生命周期", "consent": "授权", "page": "页面", "exposure": "曝光", "click": "点击",
    "search": "搜索", "funnel": "业务 / 漏斗", "perf": "性能", "error": "错误", "push": "推送",
}


def const_name(event: str) -> str:
    return event.replace(".", "_").upper()


def catalog_markdown() -> str:
    lines = [BEGIN, "", f"_由 `scripts/gen_analytics_catalog.py` 从 `taxonomy.py` 生成（schema_version={SCHEMA_VERSION}），请勿手改。_", ""]
    by_cat: dict[str, list] = {}
    for d in EVENTS.values():
        by_cat.setdefault(d.category, []).append(d)
    for cat, title in CATEGORY_TITLES.items():
        items = by_cat.get(cat)
        if not items:
            continue
        lines += [f"### {title}（{cat}）", "", "| 事件 | 说明 | 事件属性 | 对象 | 转化阶段 |", "|---|---|---|---|---|"]
        for d in items:
            props = "<br>".join(f"`{k}`: {v}" for k, v in d.props.items()) or "—"
            lines.append(f"| `{d.name}` | {d.desc} | {props} | {d.object_type or '—'} | {d.stage or '—'} |")
        lines.append("")
    lines += ["### 漏斗定义", ""]
    for key, (label, steps) in FUNNELS.items():
        chain = " → ".join(f"`{s.event}`" + (f"({s.object_type})" if s.object_type else "") for s in steps)
        lines.append(f"- **{key}** · {label}：{chain}")
    lines += ["", f"对象类型：{', '.join(f'`{o}`' for o in OBJECT_TYPES)}", "", END]
    return "\n".join(lines)


def kotlin_source() -> str:
    out = [
        "package com.dating.spark.data.analytics",
        "",
        "// GENERATED by dating-backend/scripts/gen_analytics_catalog.py — do not edit by hand.",
        f"// schema_version = {SCHEMA_VERSION}",
        "",
        "object AnalyticsEvents {",
    ]
    last = None
    for d in EVENTS.values():
        if d.category != last:
            out.append(f"    // {d.category}")
            last = d.category
        out.append(f'    const val {const_name(d.name)} = "{d.name}"')
    out += ["", f"    const val SCHEMA_VERSION = {SCHEMA_VERSION}", "}", "", "/** Object kinds accepted by the server for exposure / conversion stats. */", "object AnalyticsObject {"]
    for o in OBJECT_TYPES:
        out.append(f'    const val {o.upper()} = "{o}"')
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--kotlin", help="write Android AnalyticsEvents.kt to this path")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    doc = ROOT / "docs" / "ANALYTICS_EVENTS.md"
    text = doc.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("markers missing in docs/ANALYTICS_EVENTS.md", file=sys.stderr)
        return 2
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + catalog_markdown() + tail
    if args.check:
        return 0 if new == text else 1
    doc.write_text(new, encoding="utf-8")
    if args.kotlin:
        Path(args.kotlin).write_text(kotlin_source(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
